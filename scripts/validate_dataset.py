#!/usr/bin/env python
"""Check that a dataset's observations match what this environment produces.

Run this before pretraining on any external dataset. robosuite changes
observation conventions between releases without any error being raised, so a
policy trained on a mismatched dataset simply fails at rollout with no
diagnostic. This script catches that by replaying each demo's recorded simulator
states into the live environment and comparing observations key by key.

It also replays the recorded actions open-loop, which verifies the *action*
convention (control frame, scaling, gripper sign) independently of observations.

    python scripts/validate_dataset.py \
        --dataset data/robomimic/lift/ph/low_dim_v141.hdf5 --env Lift

Known: robosuite 1.5 negated the object-to-end-effector position sensors
relative to 1.4.1, which is what robomimic's published datasets use.
`EnvConfig.legacy_object_state` (on by default) corrects that. robosuite 1.5 also
changed PickPlace object positions from bin-relative to world coordinates, which
is *not* auto-corrected -- expect this script to report a mismatch there.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import h5py
import numpy as np

from dagger_lh.config import EnvConfig
from dagger_lh.envs import make_env, silence_robosuite_logs

TOL = 1e-4


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--env", default=None, help="defaults to the dataset's env_name")
    ap.add_argument("--demos", type=int, default=5)
    ap.add_argument("--timesteps", type=int, default=6,
                    help="evenly spaced samples per demo for the obs check")
    ap.add_argument("--replay", type=int, default=3,
                    help="demos to also replay open-loop (0 to skip)")
    ap.add_argument("--no-legacy-object-state", action="store_true",
                    help="disable the robosuite<=1.4.1 object-state sign fix")
    args = ap.parse_args()

    silence_robosuite_logs()
    f = h5py.File(args.dataset, "r")
    meta = json.loads(f["data"].attrs["env_args"])
    env_name = args.env or meta.get("env_name")
    print(f"dataset : {args.dataset}")
    print(f"env_name: {env_name}  (dataset was generated by {meta.get('env_name')})")

    cfg = EnvConfig(env_name=env_name, horizon=10_000,
                    legacy_object_state=not args.no_legacy_object_state)
    env = make_env(cfg)
    keys = list(cfg.low_dim_keys)

    demo_names = sorted((k for k in f["data"] if k.startswith("demo_")),
                        key=lambda s: int(s.split("_")[1]))[:args.demos]

    # ---------------- observation parity ----------------
    print(f"\nobservation parity  ({len(demo_names)} demos x {args.timesteps} steps)")
    worst = {k: 0.0 for k in keys}
    missing = []
    for name in demo_names:
        g = f["data"][name]
        if "states" not in g:
            print("  dataset has no `states`; cannot verify observations")
            missing = keys
            break
        states = np.asarray(g["states"])
        for t in np.linspace(0, len(states) - 1, args.timesteps).astype(int):
            mine = env.reset_to_sim_state(states[t])
            for k in keys:
                if k not in g["obs"]:
                    if k not in missing:
                        missing.append(k)
                    continue
                ref = np.asarray(g["obs"][k][t]).ravel()
                if ref.shape != mine[k].shape:
                    worst[k] = float("inf")
                    continue
                worst[k] = max(worst[k], float(np.abs(mine[k] - ref).max()))

    ok_obs = True
    for k in keys:
        if k in missing:
            print(f"  {k:24s} NOT IN DATASET")
            ok_obs = False
            continue
        good = worst[k] < TOL
        ok_obs &= good
        print(f"  {k:24s} max|diff| {worst[k]:.3e}  {'ok' if good else 'MISMATCH'}")
    if env.flipped_sensors:
        print(f"  sign-corrected sensors: {env.flipped_sensors}")

    # ---------------- action parity ----------------
    ok_act = True
    if args.replay:
        print(f"\naction convention  (open-loop replay of {args.replay} demos)")
        n_ok = 0
        for name in demo_names[:args.replay]:
            g = f["data"][name]
            acts = np.asarray(g["actions"])
            env.reset_to_sim_state(np.asarray(g["states"])[0])
            succ = False
            for a in acts:
                env.env.step(a)
                if env.env._check_success():
                    succ = True
                    break
            n_ok += succ
            print(f"  {name:10s} replay {'succeeded' if succ else 'FAILED'} "
                  f"(T={len(acts)})")
        ok_act = n_ok == args.replay
        print(f"  {n_ok}/{args.replay} demos reproduce the task")

    env.close()
    print("\n" + "=" * 62)
    if ok_obs and ok_act:
        print("VALIDATED: this dataset is safe to pretrain on for this env.")
        return 0
    print("NOT VALIDATED. Pretraining on this dataset will likely produce a")
    print("policy that trains fine but fails at rollout, because the env does")
    print("not reproduce the dataset's conventions. Fix the convention (see")
    print("dagger_lh/envs.py) or collect demonstrations with this env instead.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
